/**
  * @brief This function handles DMA2 stream0 global interrupt.
  */
void DMA2_Stream0_IRQHandler(void)
{
  /* USER CODE BEGIN DMA2_Stream0_IRQn 0 */
  /* 半传输/传输完成中断里只做一件事：把"刚完成的半缓冲起点"记到时间基准上。
     标志在这里读、不要清——清标志是下面 HAL_DMA_IRQHandler 的活。
     本中断优先级号必须大于 TIM5 的 3（当前设 4），mic_isr_half() 里会调
     lt_now_cnt()，它在等 TIM5 整秒标志时要求 TIM5 能抢占本中断，否则死等。 */
  if ((DMA2->LISR & DMA_LISR_HTIF0) != 0U)
  {
    mic_isr_half(0u);      /* 前半缓冲（索引 0..1023）刚写完 */
  }
  else if ((DMA2->LISR & DMA_LISR_TCIF0) != 0U)
  {
    mic_isr_half(1u);      /* 整个缓冲写完（索引 1024..2047） */
  }
  /* USER CODE END DMA2_Stream0_IRQn 0 */
  HAL_DMA_IRQHandler(&hdma_adc3);
  /* USER CODE BEGIN DMA2_Stream0_IRQn 1 */

  /* USER CODE END DMA2_Stream0_IRQn 1 */
}

/**
  * @brief This function handles Ethernet global interrupt.
  */
void ETH_IRQHandler(void)
{
  /* USER CODE BEGIN ETH_IRQn 0 */

  /* 收到一帧就立刻打时间戳，这是全系统最贴近硬件的一刻。

     不能改用 ethernetif.c 里的 HAL_ETH_RxLinkCallback：那个回调是由
     HAL_ETH_ReadData() 调用的，而 HAL_ETH_ReadData 运行在 ethernetif 线程
     里、不在中断里，时间戳会带上任务调度延迟（实测上百微秒且抖动很大）。

     用 DMA 的接收状态位做过滤，避免发送完成等其他中断也把时间戳冲掉。 */
  if ((ETH->DMASR & ETH_DMASR_RS) != 0U)
  {
    lt_rx_tick();
  }

  /* USER CODE END ETH_IRQn 0 */
  HAL_ETH_IRQHandler(&heth);
  /* USER CODE BEGIN ETH_IRQn 1 */

  /* USER CODE END ETH_IRQn 1 */
}

